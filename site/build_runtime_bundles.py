"""Assemble the ordered browser runtime scripts without changing their sources."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PAGE = [
    'core', 'atlas-render', 'feed-store', 'popup-navigation',
    'legacy-floor-render', 'legacy-hospital-ui', 'unit-playback',
    'waveform-detail', 'frame-and-atlas-input', 'events',
]
SCENE = [
    'core', 'model-sizes', 'load-progress', 'screens-and-tablet', 'nursing-cube', 'patients-and-monitors',
    'telemetry', 'vital-detail', 'navigation', 'unit-tour', 'events', 'frame',
    'floor-loader', 'boot',
]


def write_bundle(target, sources):
    body = ['// Generated by build_runtime_bundles.py. Edit the source parts.\n']
    for source in sources:
        body.append(f'\n// Source: {source.relative_to(ROOT)}\n')
        body.append(source.read_text())
    target.write_text(''.join(body))
    print(f'{target.relative_to(ROOT)}: {target.stat().st_size:,} bytes')


write_bundle(ROOT / 'page-runtime.js', [*(ROOT / 'page' / f'{name}.js' for name in PAGE), ROOT / 'viewer.js'])
write_bundle(ROOT / 'scene3d' / 'scene-runtime.js', [ROOT / 'scene3d' / 'parts' / f'{name}.js' for name in SCENE])
