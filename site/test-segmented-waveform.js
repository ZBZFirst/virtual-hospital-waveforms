const assert=require('node:assert/strict');
const Waveform=require('./segmented-waveform.js');
const Volume=require('./volume.js');
const Breath=require('./breath-metrics.js');
const feed={samples:5,overview:{lo:[-60],hi:[60],min:-60,max:60}};
const data=Waveform.create(feed);
assert.equal(data.flow.length,5);
assert.ok(Number.isNaN(data.flow[0]));
const latter=Waveform.parse('BS\n60,11\n-60,9\nBE\n');
Waveform.ingest(data,{sampleStart:3,sampleEnd:5},1,latter,Volume,Breath);
assert.ok(Number.isNaN(data.flow[0]));
assert.equal(data.completed.length,1);
assert.equal(data.completed[0].start,3);
const first=Waveform.parse('BS\n60,10\n60,10\n-60,8\nBE\n');
Waveform.ingest(data,{sampleStart:0,sampleEnd:3},0,first,Volume,Breath);
assert.equal(data.completed.length,2);
assert.deepEqual(data.breathStarts,[0,3]);
assert.equal(data.flow[4],-60);
assert.ok(Number.isFinite(data.volume[2]));
assert.throws(()=>Waveform.ingest(data,{sampleStart:0,sampleEnd:4},2,first,Volume,Breath),/sample count mismatch/);
const overlap=Waveform.parse('BS\n60,10\n60,10\n-60,8\nBE\nBS\n60,11\n-60,9\nBE\n');
Waveform.ingest(data,{sampleStart:0,sampleEnd:5},2,overlap,Volume,Breath);
assert.equal(data.completed.length,2,'overlap does not duplicate completed breaths');
assert.equal(data.breathStarts.length,2,'overlap does not duplicate markers');
console.log('segmented waveform tests passed');
