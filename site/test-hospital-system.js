const assert=require('node:assert/strict');
const H=require('./hospital-system.js');
const manifest=require('./manifest.json');
const model=H.createModel(manifest.entries,manifest.sampleRate);
assert.equal(model.feedRegistry.size,145);
assert.equal(model.feedMetadata.size,145);
assert.equal(model.unitDefinitions.length,25);
assert.equal(model.baseline.hospitalDefinitions.length,7);
assert.equal(model.baseline.version,3);
assert.deepEqual(model.baseline.floorUnits.hospital_005,['unit_17','unit_18','unit_19','unit_20']);
assert.equal(H.validateState(model.baseline,model).length,0);
assert.equal(H.occupancy(model.baseline,model).unassigned,0);
assert.ok(model.unitDefinitions.every(unit=>unit.bed_ids.length===6));
assert.equal(new Set(Object.values(model.baseline.placements).filter(Boolean)).size,145);
const oldPlacements=Object.fromEntries(model.unitDefinitions.slice(0,19).flatMap(unit=>
  Array.from({length:8},(_,index)=>[H.bedId(unit.unit_id,index+1),null])));
for(const entry of manifest.entries)oldPlacements[H.bedId(H.unitId(entry.unit),entry.room)]=entry.name;
const v2=structuredClone(model.baseline);
v2.version=2;v2.placements=oldPlacements;
v2.hospitalDefinitions=v2.hospitalDefinitions.slice(0,5);
v2.hospitalUnits=Object.fromEntries(Object.entries(v2.hospitalUnits).slice(0,5));
v2.floorUnits=Object.fromEntries(Object.entries(v2.floorUnits).slice(0,5));
v2.hospitalUnits.hospital_005.pop();v2.floorUnits.hospital_005[3]=null;
const upgraded=H.loadState(JSON.stringify(v2),model);
assert.equal(upgraded.migrated,true);
assert.deepEqual(upgraded.issues,[]);
assert.equal(new Set(Object.values(upgraded.state.placements).filter(Boolean)).size,145);
assert.equal(H.validateState(upgraded.state,model).length,0);
assert.deepEqual(model.baseline.hospitalDefinitions.map(h=>H.occupancy(model.baseline,model).hospitals[h.hospital_id].units),[4,4,4,4,4,4,1]);
const first=model.originalOrder[0];
assert.equal(model.feedRegistry.get(first).source_id,manifest.entries[0].id);
assert.equal(model.feedMetadata.get(first).duration_seconds,manifest.entries[0].samples/50);
assert.equal(model.feedMetadata.get(first).total_breaths,manifest.entries[0].breaths);
for(const preset of ['original','duration','breaths'])for(const direction of ['asc','desc']){
  const a=H.propose(model,model.baseline,preset,direction);
  const b=H.propose(model,model.baseline,preset,direction);
  assert.deepEqual(a,b,'proposals are deterministic');
  assert.equal(H.validateProposal(a,model).length,0);
  assert.equal(new Set(Object.values(a.placements).filter(Boolean)).size,145);
}
const shortest=H.sortFeeds(model,model.baseline,'duration','asc').ordered;
const longest=H.sortFeeds(model,model.baseline,'duration','desc').ordered;
assert.ok(model.feedMetadata.get(shortest[0]).duration_seconds<=model.feedMetadata.get(shortest.at(-1)).duration_seconds);
assert.ok(model.feedMetadata.get(longest[0]).duration_seconds>=model.feedMetadata.get(longest.at(-1)).duration_seconds);
const fewest=H.sortFeeds(model,model.baseline,'breaths','asc').ordered;
const most=H.sortFeeds(model,model.baseline,'breaths','desc').ordered;
assert.ok(model.feedMetadata.get(fewest[0]).total_breaths<=model.feedMetadata.get(fewest.at(-1)).total_breaths);
assert.ok(model.feedMetadata.get(most[0]).total_breaths>=model.feedMetadata.get(most.at(-1)).total_breaths);
const changed=H.applyProposal(model.baseline,H.propose(model,model.baseline,'duration','desc'),model);
assert.ok(changed.events.length>0);
assert.equal(H.validateState(changed.state,model).length,0);
assert.deepEqual(H.loadState(JSON.stringify(changed.state),model).state,changed.state,'saved layout restores');
assert.deepEqual(H.propose(model,changed.state,'manual').placements,changed.state.placements);
assert.deepEqual(model.baseline.placements,H.loadState(null,model).state.placements,'original layout migrates');
const oldLayout=structuredClone(model.baseline);oldLayout.version=1;delete oldLayout.floorUnits;
const migrated=H.loadState(JSON.stringify(oldLayout),model);
assert.equal(migrated.migrated,true);
assert.deepEqual(migrated.state.floorUnits,model.baseline.floorUnits);
const extra=H.createHospital(model.baseline,'Teaching Hospital');
const extraId=extra.hospitalDefinitions.at(-1).hospital_id;
const moved=H.assignUnit(extra,'unit_01',extraId,model);
assert.ok(moved.hospitalUnits[extraId].includes('unit_01'));
assert.equal(moved.placements[H.bedId('unit_01',1)],first,'unit move retains feed');
assert.equal(H.occupancy(moved,model).hospitals[extraId].feeds,6);
assert.equal(H.floorForUnit(moved,'unit_01').floor_id,H.floorId(extraId,1));
const floorMove=H.assignUnitToFloor(model.baseline,'unit_01','hospital_007',2,model);
assert.equal(floorMove.floorUnits.hospital_007[1],'unit_01');
assert.equal(floorMove.floorUnits.hospital_001[0],null);
assert.equal(floorMove.placements[H.bedId('unit_01',1)],first);
assert.ok(H.validateState(floorMove,model).length===0);
assert.throws(()=>H.assignUnitToFloor(model.baseline,'unit_01','hospital_002',1,model),/occupied/);
assert.throws(()=>H.assignUnit(model.baseline,'unit_01','hospital_002',model),/four units/);
const removed=H.removeUnit(model.baseline,'unit_01',model);
assert.ok(!Object.values(removed.hospitalUnits).some(ids=>ids.includes('unit_01')));
assert.equal(removed.floorUnits.hospital_001[0],null);
assert.equal(removed.placements[H.bedId('unit_01',1)],first);
assert.equal(extra.hospitalDefinitions.at(-1).display_name,'Teaching Hospital');
assert.equal(H.renameHospital(extra,extra.hospitalDefinitions.at(-1).hospital_id,'Renamed').hospitalDefinitions.at(-1).display_name,'Renamed');
const invalid=structuredClone(model.baseline);
invalid.placements[H.bedId('unit_01',2)]=first;
assert.ok(H.validateState(invalid,model).some(x=>x.includes('multiple beds')));
invalid.placements[H.bedId('unit_01',2)]='missing.csv';
assert.ok(H.loadState(JSON.stringify(invalid),model).issues.some(x=>x.includes('Missing feed')));
const tiny=H.createModel([{name:'one.csv',id:'source',samples:100,breaths:2,unit:1,room:1}],50);
assert.equal(H.occupancy(tiny.baseline,tiny).units.unit_01,1);
const empty=H.createModel([],50);
assert.equal(empty.feedRegistry.size,0);
assert.equal(empty.unitDefinitions.length,0);
assert.equal(empty.baseline.hospitalDefinitions.length,0);
assert.equal(H.propose(empty,empty.baseline,'original').unassigned.length,0);
const noMetadata=H.createModel([{name:'unknown.csv',unit:1,room:1}],null);
assert.equal(noMetadata.feedMetadata.get('unknown.csv').duration_seconds,null);
assert.equal(noMetadata.feedMetadata.get('unknown.csv').total_breaths,null);
assert.deepEqual(H.propose(noMetadata,noMetadata.baseline,'duration').missingMetadata,['unknown.csv']);
assert.throws(()=>H.createModel([{name:'a.csv',unit:1,room:1},{name:'b.csv',unit:1,room:1}],50),/Duplicate original bed/);
const full=H.createModel(Array.from({length:6},(_,i)=>({name:`f${i}.csv`,unit:1,room:i+1})),50);
full.feedRegistry.set('overflow.csv',{feed_id:'overflow.csv',source_file:'overflow.csv'});
full.feedMetadata.set('overflow.csv',{duration_seconds:null,total_breaths:null});
full.originalOrder.push('overflow.csv');
const proposal=H.propose(full,full.baseline,'original');
assert.deepEqual(proposal.unassigned,['overflow.csv']);
assert.equal(H.occupancy(H.applyProposal(full.baseline,proposal,full).state,full).unassigned,1);
const duplicate=structuredClone(proposal);
duplicate.placements[H.bedId('unit_01',2)]=duplicate.placements[H.bedId('unit_01',1)];
assert.ok(H.validateProposal(duplicate,full).some(x=>x.includes('Duplicate feed')));
const emptyUnit=structuredClone(model.baseline);
for(const bed of model.unitDefinitions[0].bed_ids)emptyUnit.placements[bed]=null;
assert.equal(H.occupancy(emptyUnit,model).units.unit_01,0);
const invalidUnit=structuredClone(model.baseline);
invalidUnit.hospitalUnits.hospital_001.push('missing_unit');
assert.ok(H.loadState(JSON.stringify(invalidUnit),model).issues.some(x=>x.includes('Unknown unit')));
const invalidFloor=structuredClone(model.baseline);
invalidFloor.floorUnits.hospital_001[0]='unit_09';
assert.ok(H.loadState(JSON.stringify(invalidFloor),model).issues.some(x=>x.includes('Floor slots differ')));
console.log('Hospital system tests passed');
